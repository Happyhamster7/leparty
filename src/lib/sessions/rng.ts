/**
 * Dice that can be rolled again. Every action is given a seed, the seed
 * is logged with it, and the same seed always deals the same rolls, so
 * a night can be replayed from its log. (mulberry32.)
 */
export function seededRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
